public class DoWhileSchleife_1 {
    
    public static void main(String[] args) {
        int i = 0;
// do - while Schleife - läuft immer minedstens einmal durch und prüft dann die bedingung.
        do {
            System.out.println("Durchlauf: " + i);
            i++;

        } while (i<=5);
        
    }
}
