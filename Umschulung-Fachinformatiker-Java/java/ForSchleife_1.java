public class ForSchleife_1 {
    
    public static void main(String[] args) {
    
    
           
for(int i = 0 ; i <= 10; i++){
    System.out.println("Durchlauf: " + i);
}
System.out.println();

for (int i = 0; i < 100; i+=10) {
    System.out.println( i + " ");
        }
System.out.println();

//Rückwärts zählen
for ( int i =10; i > 0; i--){
    System.out.println( i);
        }
System.out.println();

for (int i = 0; i <= 20; i +=2) {
    System.out.print(i + " ");
        }

    }
}
